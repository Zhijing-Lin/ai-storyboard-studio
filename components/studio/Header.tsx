import type { Step } from "@/lib/storyboard/types";

const STEPS: { id: Step; label: string; short: string }[] = [
  { id: "input", label: "Project Input", short: "Input" },
  { id: "outline", label: "Design Outline", short: "Outline" },
  { id: "storyboard", label: "Storyboard", short: "Storyboard" },
];

export function Header({
  step,
  maxStepIndex,
  onNavigate,
  mockMode,
}: {
  step: Step;
  maxStepIndex: number;
  onNavigate: (step: Step) => void;
  mockMode: boolean;
}) {
  const currentIndex = STEPS.findIndex((s) => s.id === step);
  return (
    <header className="sticky top-0 z-20 border-b border-line bg-paper/95 shadow-soft backdrop-blur-md">
      <div className="mx-auto flex max-w-7xl flex-col gap-3 px-4 py-3.5 sm:px-6 md:flex-row md:items-center md:justify-between lg:px-8">
        <div className="flex items-center gap-3">
          <div className="relative flex size-9 items-center justify-center rounded-xl bg-forest font-display text-sm font-bold tracking-tight text-paper">
            AS
            <span aria-hidden className="absolute -right-0.5 -top-0.5 size-2.5 rounded-full bg-ember ring-2 ring-paper" />
          </div>
          <div>
            <p className="font-display text-[17px] font-semibold leading-tight tracking-[-0.01em] text-forest">
              AI Storyboard Studio
            </p>
            <p className="text-xs text-ink-muted">Prototype v0.1 · Storyline 360 storyboards</p>
          </div>
        </div>

        <nav aria-label="Workflow steps">
          <ol className="flex items-center gap-1 sm:gap-1.5">
            {STEPS.map((s, i) => {
              const reachable = i <= maxStepIndex;
              const active = i === currentIndex;
              const done = i < currentIndex;
              return (
                <li key={s.id} className="flex items-center gap-1 sm:gap-1.5">
                  {i > 0 && (
                    <span aria-hidden className={`h-0.5 w-3 rounded-full sm:w-5 ${i <= currentIndex ? "bg-forest" : "bg-line"}`} />
                  )}
                  <button
                    type="button"
                    disabled={!reachable}
                    onClick={() => onNavigate(s.id)}
                    aria-current={active ? "step" : undefined}
                    className={`flex items-center gap-2 rounded-full py-1 pl-1 pr-3 text-sm transition-colors focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-forest disabled:cursor-not-allowed ${
                      active
                        ? "bg-forest font-semibold text-paper shadow-soft"
                        : reachable
                          ? "font-medium text-forest hover:bg-forest-tint"
                          : "text-ink-subtle"
                    }`}
                  >
                    <span
                      className={`flex size-6 shrink-0 items-center justify-center rounded-full font-display text-xs font-bold ${
                        active
                          ? "bg-paper text-forest"
                          : done
                            ? "bg-forest-tint text-forest ring-1 ring-inset ring-forest/25"
                            : "bg-cream text-ink-subtle ring-1 ring-inset ring-line"
                      }`}
                    >
                      {done ? "✓" : i + 1}
                    </span>
                    <span className="hidden sm:inline">{s.label}</span>
                    <span className="sm:hidden">{s.short}</span>
                  </button>
                </li>
              );
            })}
          </ol>
        </nav>
      </div>
      <div className="border-t border-ember/25 bg-ember-tint">
        <p className="mx-auto flex max-w-7xl items-start gap-2 px-4 py-2 text-xs leading-5 text-ink-soft sm:px-6 lg:px-8">
          <span aria-hidden className="mt-[7px] size-1.5 shrink-0 rounded-full bg-ember" />
          <span>
            <strong className="font-semibold text-ember-dark">{mockMode ? "Mock mode:" : "Prototype notice:"}</strong>{" "}
            {mockMode
              ? "AI generation is simulated with mock data. No AI model is called and nothing is saved — refreshing the page resets your work."
              : "Drafts are generated by OpenAI and can contain errors — review every item before use. Nothing is saved — refreshing the page resets your work."}
          </span>
        </p>
      </div>
    </header>
  );
}
